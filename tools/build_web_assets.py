"""Embed reproducible, locally served gzip assets in the ESPHome web adapter."""
import argparse
import gzip
import io
import re
import zlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT / "components/dsc_web/generated_assets.h"
FILES=(("index", "index.html"), ("css", "app.css"), ("js", "app.js"))


def generate():
    sections=["// Generated by tools/build_web_assets.py; edit web/ sources instead.\n#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace dsc_web_assets {\n"]
    total=0
    for symbol,name in FILES:
        raw=(ROOT / "web" / name).read_bytes()
        out=io.BytesIO()
        with gzip.GzipFile(filename="",mode="wb",fileobj=out,compresslevel=9,mtime=0) as archive:
            archive.write(raw)
        compressed=out.getvalue(); total+=len(compressed)
        data=", ".join(f"0x{byte:02x}" for byte in compressed)
        sections.append(f"inline constexpr std::uint8_t {symbol}[] = {{{data}}};\n")
    sections.append("}  // namespace dsc_web_assets\n")
    if total>100*1024:
        raise RuntimeError(f"Compressed assets exceed 100 KiB: {total}")
    return "".join(sections),total


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    result,size=generate()
    if args.check:
        # DEFLATE output can differ across zlib versions even with fixed gzip
        # metadata. Verify the actual embedded payloads, not compressor bytes.
        text=OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        embedded=0
        for symbol,name in FILES:
            match=re.search(r"inline constexpr std::uint8_t " + symbol + r"\[\] = \{([^}]*)\};",text)
            try:
                if not match: raise ValueError("missing asset")
                compressed=bytes(int(value.strip(),16) for value in match.group(1).split(","))
                embedded+=len(compressed)
                if gzip.decompress(compressed)!=(ROOT / "web" / name).read_bytes():
                    raise ValueError("asset content changed")
            except (ValueError, OSError, EOFError, zlib.error):
                raise SystemExit("Generated web assets are stale or invalid; run tools/build_web_assets.py")
        if embedded>100*1024:
            raise SystemExit("Embedded web assets exceed the 100 KiB budget")
        size=embedded
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True)
        OUTPUT.write_text(result,encoding="utf-8",newline="\n")
    print(f"Embedded web assets: {size} compressed bytes / 102400-byte budget")


if __name__=="__main__": main()
